#!/usr/bin/env python3
"""Read-only vote tally: counts each proposal's vote files directly (yes/no/missing/malformed).
Generated by a script, not by a seat. Writes nothing unless --out is given."""
import json, re, sys, datetime
from pathlib import Path
F = Path(__file__).resolve().parent.parent / "founders"

def tally(votes_dir=None, props_dir=None):
    votes_dir = Path(votes_dir or F/"votes"); props_dir = Path(props_dir or F/"proposals")
    props = sorted(p.name for p in props_dir.glob("PROPOSAL_*.md"))
    rows = []
    for pr in props:
        yes, no, bad, proto, seen = [], [], [], [], set()
        for v in sorted(votes_dir.glob("*.json")):
            try: d = json.loads(v.read_text())
            except Exception:
                if v.name.startswith(pr[:-3]): bad.append(v.name)
                continue
            if "ranking" in d or d.get("proposal") != pr: continue
            s = d.get("seat")
            if not isinstance(s, int) or not 1 <= s <= 5 or not isinstance(d.get("support"), bool): bad.append(v.name); continue
            if s in seen: bad.append(v.name + " (duplicate seat)"); continue
            seen.add(s); (yes if d["support"] else no).append(s)
            if d.get("prototype"): proto.append(s)
        missing = [s for s in range(1, 6) if s not in seen]
        rows.append(dict(proposal=pr, yes=sorted(yes), no=sorted(no), missing=missing, malformed=bad, prototype_votes=sorted(proto)))
    return rows

def render(rows, date):
    out = [f"# Vote tally check (generated by script, not by a seat)", "",
           f"Checked {date} by counting each vote file directly. Not human-verified. Disagreements with any agenda are marked, not fixed.", "",
           "| Proposal | Yes | No | Missing seats | Malformed | Votes marked prototype |", "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['proposal']} | {len(r['yes'])} | {len(r['no'])} | {r['missing'] or '-'} | {r['malformed'] or '-'} | {r['prototype_votes'] or '-'} |")
    out += ["", "Adoption needs 4 yes (Founding Convention)."]
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    rows = tally(); date = datetime.date.today().isoformat(); txt = render(rows, date)
    if "--out" in sys.argv: Path(sys.argv[sys.argv.index("--out")+1]).write_text(txt)
    else: print(txt)
